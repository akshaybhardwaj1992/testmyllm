# ------------------------------------------------------------------ fake judge
class FakeJudge:
    """Configurable deterministic judge shared by the fake engines."""

    def __init__(self):
        self.calls: list[tuple[str, str, int | None]] = []
        self.scores: dict[tuple[str, str], float | list[float]] = {}
        self.errors: set[tuple[str, str]] = set()
        self.cost = 0.001
        self._iters: dict[tuple[str, str], itertools.cycle] = {}

    def next_score(self, metric: str, engine: str) -> float:
        v = self.scores.get((metric, engine), 0.9)
        if isinstance(v, list):
            cached = self._iters.get((metric, engine))
            if cached is None or cached[0] is not v:  # restart the cycle when the list is replaced
                cached = (v, itertools.cycle(v))
                self._iters[(metric, engine)] = cached
            return next(cached[1])
        return v


def _fake_engine(name: str, judge: FakeJudge) -> type[Evaluator]:
    class Fake(Evaluator):
        engine = name

        @staticmethod
        def version() -> str:
            return "0.0-test"

        async def score(self, metric, inputs, threshold):
            judge.calls.append((metric, name, None))
            if (metric, name) in judge.errors:
                raise RuntimeError("judge output could not be parsed (sk-or-v1-abcdefghijklmnop)")
            return EngineScore(
                score=judge.next_score(metric, name), reason=f"{name} says ok",
                input_tokens=100, output_tokens=10, cost_usd=judge.cost,
            )

    return Fake


